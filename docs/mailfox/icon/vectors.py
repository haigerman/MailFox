# Writes the traced line art as Android vector drawables.
import sys

work, res = sys.argv[1], sys.argv[2]


def vector_xml(name, size_dp, viewport, content, color, comment):
    d = open(f"{work}/{name}.path").read()
    x0, y0, x1, y1 = map(int, open(f"{work}/{name}.bbox").read().split())
    w, h = x1 - x0, y1 - y0
    s = content / max(w, h)
    tx = viewport / 2 - s * (x0 + w / 2)
    ty = viewport / 2 - s * (y0 + h / 2)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} -->
<vector
    xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}"
    >
    <group
        android:scaleX="{s:.6f}"
        android:scaleY="{s:.6f}"
        android:translateX="{tx:.4f}"
        android:translateY="{ty:.4f}"
        >
        <path
            android:fillColor="{color}"
            android:fillType="evenOdd"
            android:pathData="{d}"
            />
    </group>
</vector>
'''


open(f"{res}/drawable/ic_mailfox_notification.xml", "w").write(
    vector_xml("lineart_bold", 24, 24, 22, "#FFFFFFFF", "MailFox status bar icon: fox line art with @ (generated by docs/mailfox/icon)"))
open(f"{res}/drawable/ic_app_logo_monochrome.xml", "w").write(
    vector_xml("lineart_thin", 108, 108, 62, "#FF000000", "MailFox monochrome (themed) launcher icon (generated by docs/mailfox/icon)"))
print("ok")
